//1D array// 1D array
#include <stdio.h>

int main() {
    int i;

    // Declare and initialize the array
    int marks[7] = {10000, 9000, 8000, 7000, 6000, 5000, 4000};

    // Display array elements using a for loop
    for (i = 0; i < 7; i++) {
        printf("%d\n", marks[i]);
    }

    return 0;
}




















    